package com.liskovsoft.smartyoutubetv2.common.exoplayer;

import com.google.android.exoplayer2.C;
import com.google.android.exoplayer2.source.dash.DashSegmentIndex;
import com.google.android.exoplayer2.source.dash.manifest.AdaptationSet;
import com.google.android.exoplayer2.source.dash.manifest.DashManifest;
import com.google.android.exoplayer2.source.dash.manifest.DashManifestParser2;
import com.google.android.exoplayer2.source.dash.manifest.Representation;
import com.google.android.exoplayer2.util.MimeTypes;
import com.liskovsoft.mediaserviceinterfaces.data.MediaFormat;
import com.liskovsoft.mediaserviceinterfaces.data.MediaItemFormatInfo;
import com.liskovsoft.mediaserviceinterfaces.data.MediaSubtitle;

import org.junit.Test;
import org.junit.runner.RunWith;
import org.robolectric.RobolectricTestRunner;
import org.robolectric.annotation.Config;

import java.lang.reflect.Proxy;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Collections;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertNotNull;
import static org.junit.Assert.assertTrue;

/**
 * A live stream's captions are text/mp4 formats beside its audio and video (issue yuliskov/SmartTube#5681)
 */
@RunWith(RobolectricTestRunner.class)
@Config(sdk = 28)
public class LiveCaptionManifestTest {
    private static final String LIVE_URL = "https://rr1---sn-test.googlevideo.com/videoplayback?source=yt_live_broadcast&live=1&itag=";
    private static final int START_SEGMENT_NUM = 9092;

    @Test
    public void webVttCaptionFormat_isATextTrackSegmentedLikeTheAudio() {
        DashManifest manifest = parse(liveInfo(null, audio(), caption("387", "English", ".en.eEY6OEpapPo", null)));

        List<AdaptationSet> textSets = setsOfType(manifest, C.TRACK_TYPE_TEXT);
        assertEquals(1, textSets.size());

        Representation representation = textSets.get(0).representations.get(0);
        assertEquals(MimeTypes.APPLICATION_MP4, representation.format.containerMimeType);
        assertEquals(MimeTypes.TEXT_VTT, representation.format.sampleMimeType);
        assertEquals(".en.eEY6OEpapPo", representation.format.id);
        assertEquals("english", representation.format.language); // Format lowercases it, as it does a video's subtitles
        assertEquals(C.ROLE_FLAG_SUBTITLE, representation.format.roleFlags);
        assertEquals(0, representation.format.selectionFlags);

        // Fetched by segment number, as the audio is
        DashSegmentIndex index = representation.getIndex();
        assertNotNull(index);
        assertEquals(START_SEGMENT_NUM, index.getFirstSegmentNum());
        String url = index.getSegmentUrl(START_SEGMENT_NUM).resolveUriString(representation.baseUrl);
        assertTrue(url, url.startsWith(LIVE_URL + "387"));
        assertTrue(url, url.endsWith("&sq=" + START_SEGMENT_NUM));

        Representation audio = setsOfType(manifest, C.TRACK_TYPE_AUDIO).get(0).representations.get(0);
        assertEquals(audio.getIndex().getTimeUs(START_SEGMENT_NUM), index.getTimeUs(START_SEGMENT_NUM));
        assertEquals(audio.getIndex().getDurationUs(START_SEGMENT_NUM, C.TIME_UNSET), index.getDurationUs(START_SEGMENT_NUM, C.TIME_UNSET));
    }

    @Test
    public void autoGeneratedCaptions_areNamedAsAVideosAutoGeneratedSubtitles() {
        DashManifest manifest = parse(liveInfo(null, audio(), caption("387", "English (auto-generated)*", "a.en.V0RXtqgInPU", null)));

        assertEquals("english (auto-generated)*", setsOfType(manifest, C.TRACK_TYPE_TEXT).get(0).representations.get(0).format.language);
    }

    @Test
    public void captionWithoutTrackInfo_fallsBackToTheItagAndLanguage() {
        DashManifest manifest = parse(liveInfo(null, audio(), caption("387", null, null, "en")));

        Representation representation = setsOfType(manifest, C.TRACK_TYPE_TEXT).get(0).representations.get(0);
        assertEquals("387", representation.format.id);
        assertEquals("en", representation.format.language);
    }

    @Test
    public void srv3AndOtherCaptionFormats_areLeftOut() {
        DashManifest manifest = parse(liveInfo(null, audio(),
                caption("386", "English", ".en.eEY6OEpapPo", null), caption("406", "English", ".en.eEY6OEpapPo", null)));

        assertTrue(setsOfType(manifest, C.TRACK_TYPE_TEXT).isEmpty());
        assertEquals(1, setsOfType(manifest, C.TRACK_TYPE_AUDIO).size());
    }

    @Test
    public void videoSubtitles_areListedInsteadOfTheLiveCaptions() {
        MediaSubtitle subtitle = proxy(MediaSubtitle.class, map(
                "getBaseUrl", "https://www.youtube.com/api/timedtext?v=test&lang=en",
                "getMimeType", MimeTypes.TEXT_VTT,
                "getName", "English",
                "getLanguageCode", "en",
                "getVssId", ".en"));

        DashManifest manifest = parse(liveInfo(Collections.singletonList(subtitle), audio(), caption("387", "English", ".en.eEY6OEpapPo", null)));

        List<AdaptationSet> textSets = setsOfType(manifest, C.TRACK_TYPE_TEXT);
        assertEquals(1, textSets.size());
        assertEquals(".en", textSets.get(0).representations.get(0).format.id);
    }

    private static DashManifest parse(MediaItemFormatInfo formatInfo) {
        return new DashManifestParser2().parse(formatInfo);
    }

    private static List<AdaptationSet> setsOfType(DashManifest manifest, int type) {
        List<AdaptationSet> result = new ArrayList<>();

        for (AdaptationSet set : manifest.getPeriod(0).adaptationSets) {
            if (set.type == type) {
                result.add(set);
            }
        }

        return result;
    }

    private static MediaItemFormatInfo liveInfo(List<MediaSubtitle> subtitles, MediaFormat... formats) {
        return proxy(MediaItemFormatInfo.class, map(
                "getVideoId", "1YXN4bsps9Y",
                "getLengthSeconds", "0",
                "isLive", true,
                "getAdaptiveFormats", Arrays.asList(formats),
                "getSubtitles", subtitles,
                "getSegmentDurationUs", 5_000_000,
                "getStartSegmentNum", START_SEGMENT_NUM));
    }

    private static MediaFormat audio() {
        return proxy(MediaFormat.class, map(
                "getITag", "140",
                "getMimeType", "audio/mp4; codecs=\"mp4a.40.2\"",
                "getUrl", LIVE_URL + "140",
                "getBitrate", "144000",
                "getTargetDurationSec", 5));
    }

    private static MediaFormat caption(String itag, String name, String vssId, String language) {
        return proxy(MediaFormat.class, map(
                "getITag", itag,
                "getMimeType", "text/mp4; codecs=\"unknown\"",
                "getUrl", LIVE_URL + itag,
                "getCaptionName", name,
                "getCaptionVssId", vssId,
                "getLanguage", language,
                "getTargetDurationSec", 5));
    }

    private static Map<String, Object> map(Object... keysAndValues) {
        Map<String, Object> result = new HashMap<>();

        for (int i = 0; i < keysAndValues.length; i += 2) {
            result.put((String) keysAndValues[i], keysAndValues[i + 1]);
        }

        return result;
    }

    /**
     * Answers the named getters, every other call gets the type's default
     */
    @SuppressWarnings("unchecked")
    private static <T> T proxy(Class<T> type, Map<String, Object> values) {
        return (T) Proxy.newProxyInstance(type.getClassLoader(), new Class<?>[]{type}, (self, method, args) -> {
            if (values.containsKey(method.getName())) {
                return values.get(method.getName());
            } else if ("hashCode".equals(method.getName())) {
                return System.identityHashCode(self);
            } else if ("equals".equals(method.getName())) {
                return self == args[0];
            } else if ("toString".equals(method.getName())) {
                return type.getSimpleName() + values;
            }

            Class<?> returnType = method.getReturnType();

            if (returnType == boolean.class) {
                return false;
            } else if (returnType == int.class) {
                return 0;
            } else if (returnType == long.class) {
                return 0L;
            } else if (returnType == float.class) {
                return 0f;
            }

            return null;
        });
    }
}
